TEST_DIR_NAMES = {"test", "tests", "spec", "specs", "__tests__", "e2e", "it"}
TEST_FILE_RE = re.compile(
    r"(^|[./\\_-])(test|tests|spec|specs)[./\\_-]|(_test|_spec|\.test|\.spec|Test|Specs?)\.[A-Za-z]+$"
)


def language_of(path: str) -> str | None:
    _, ext = os.path.splitext(path)
    return LANGUAGES.get(ext.lower())


def should_skip_dir(name: str) -> bool:
    if name in SKIP_DIRS:
        return True
    return name.endswith(".egg-info")


def is_skipped_file(path: str) -> bool:
    return path.endswith(SKIP_FILE_SUFFIXES)


_PY_TEST_MARKERS = ("def test_", "class Test", "unittest.TestCase", "assertEqual")


def is_test_path(rel_path: str, root: str | None = None) -> bool:
    parts = rel_path.replace("\\", "/").split("/")
    if any(p.lower() in TEST_DIR_NAMES for p in parts[:-1]):
        return True
    base = parts[-1]
    if not TEST_FILE_RE.search("/" + base):
        return False
    # python's test_* convention is ambiguous (a helper module can be named
    # test_probe.py). Only call it a test if it actually looks like one.
    if base.endswith((".py", ".pyi")) and not any(p in parts[:-1] for p in TEST_DIR_NAMES):
        probe_root = root or os.getcwd()
        full = os.path.join(probe_root, rel_path)
        try:
            with open(full, "r", encoding="utf-8", errors="replace") as fh:
                body = fh.read()
        except OSError:
            return True
        return any(m in body for m in _PY_TEST_MARKERS)
    return True


def is_generated(path: str) -> bool:
    """Heuristic: file looks machine-generated rather than hand-written."""
    head = ""
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            head = fh.read(2000)
    except OSError:
        return False
    markers = (
        "auto-generated", "autogenerated", "automatically generated",
        "@generated", "do not edit", "generated by", "code generated by",
        "this file was generated",
    )
    low = head.lower()
    return any(m in low for m in markers)


def iter_files(root: str, follow_symlinks: bool = False) -> Iterator[str]:
    """Yield paths of interesting files relative to root, skipping noise dirs."""
    for dirpath, dirnames, filenames in os.walk(root, followlinks=follow_symlinks):
        dirnames[:] = sorted(d for d in dirnames if not should_skip_dir(d))
        for name in sorted(filenames):
            if is_skipped_file(name):
                continue
            full = os.path.join(dirpath, name)
            if os.path.islink(full) and not follow_symlinks:
                continue
            if os.path.getsize(full) > 2_000_000:
                continue
            yield os.path.relpath(full, root).replace(os.sep, "/")


def read_text(path: str) -> str:
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        return fh.read()


def read_lines(path: str) -> list[str]:
    return read_text(path).splitlines()


