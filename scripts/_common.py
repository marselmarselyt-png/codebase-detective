# --------------------------------------------------------------------------
# Import / export extraction (regex based; language aware where cheap)
# --------------------------------------------------------------------------

_IMPORT_PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    # python:  from x import a, b   |  import x.y as z
    ("python", re.compile(r"^\s*(?:from\s+([.\w]+)\s+import\s+(.+)|import\s+([.\w]+))")),
    # js/ts: import ... from 'x' | import 'x' | export ... from 'x'
    ("js", re.compile(r"""^\s*(?:import|export)\b[^'"`]*?from\s+['"]([^'"]+)['"]""")),
    ("js", re.compile(r"""^\s*import\s+['"]([^'"]+)['"]""")),
    # go
    ("go", re.compile(r"""^\s*import\s+"([^"]+)""")),
    # rust
    ("rust", re.compile(r"^\s*(?:pub\s+)?use\s+([\w:]+)")),
]

_EXPORT_PATTERNS: dict[str, list[re.Pattern[str]]] = {
    "python": [
        re.compile(r"^\s*def\s+(\w+)"),
        re.compile(r"^\s*class\s+(\w+)"),
        re.compile(r"^\s*__all__\s*=\s*\[(.*)\]"),
    ],
    "js": [
        re.compile(r"^\s*export\s+(?:default\s+)?(?:async\s+)?function\s+(\w+)"),
        re.compile(r"^\s*export\s+(?:const|let|var|class)\s+(\w+)"),
        re.compile(r"^\s*export\s*\{([^}]*)\}"),
    ],
    "go": [
        re.compile(r"^\s*func\s+(?:\([^)]*\)\s*)?(\w+)"),
        re.compile(r"^\s*type\s+(\w+)"),
    ],
    "rust": [re.compile(r"^\s*pub\s+(?:fn|struct|enum|trait|const|static|mod|type)\s+(\w+)")],
    "java": [re.compile(r"^\s*public\s+(?:static\s+)?(?:final\s+)?[\w<>\[\],.]+\s+(\w+)\s*\(")],
    "ruby": [re.compile(r"^\s*def\s+([\w.?!]+)")],
}


def strip_comments_python(line: str) -> str:
    out, in_s, q = [], False, ""
    i = 0
    while i < len(line):
        c = line[i]
        if in_s:
            if c == "\\":
                i += 2
                continue
            if c == q:
                in_s = False
            i += 1
            continue
        if c in "\"'":
            in_s, q = True, c
            out.append(c)
            i += 1
            continue
        if c == "#":
            break
        out.append(c)
        i += 1
    return "".join(out)


def dialect_of(path: str) -> str:
    """Collapse an extension to the dialect used by the pattern tables."""
    ext = os.path.splitext(path)[1].lower()
    if ext in (".py", ".pyi"):
        return "python"
    if ext in (".js", ".mjs", ".cjs", ".jsx", ".ts", ".tsx"):
        return "js"
    return ext.lstrip(".")


def extract_imports(path: str, lines: list[str]) -> list[str]:
    dialect = dialect_of(path)
    pats = [p for d, p in _IMPORT_PATTERNS if d == dialect]
    if not pats:
        return []
    mods: list[str] = []
    for raw in lines:
        line = strip_comments_python(raw) if dialect == "python" else raw
        for pat in pats:
            m = pat.match(line)
            if not m:
                continue
            if dialect == "python":
                from_mod, names, plain = m.group(1), m.group(2), m.group(3)
                if from_mod is not None:
                    if set(from_mod) == {"."}:  # `from . import a, b`
                        for name in re.split(r"[,\s]+", names or ""):
                            if name and name != "*":
                                mods.append(from_mod + name)
                    else:
                        mods.append(from_mod.strip())
                elif plain:
                    mods.append(plain.strip())
            else:
                mod = next((g for g in m.groups() if g), "")
                if mod:
                    mods.append(mod.strip())
            break
    seen, out = set(), []
    for m in mods:
        if m not in seen:
            seen.add(m)
            out.append(m)
    return out


def extract_exports(path: str, lines: list[str]) -> list[str]:
    key = dialect_of(path)
    pats = _EXPORT_PATTERNS.get(key, [])
    names: list[str] = []
    for raw in lines:
        line = strip_comments_python(raw) if key == "python" else raw
        if key == "python" and line[:1] in (" ", "\t"):
            continue  # nested def/class is a method, not a module export
        for pat in pats:
            m = pat.match(line)
            if m:
                group = m.group(1) or ""
                for name in re.split(r"[,\s]+", group):
                    name = name.strip().strip("'\"")
                    if name and name != "*":
                        names.append(name.split(".")[-1])
                break
    seen, out = set(), []
    for n in names:
        if n not in seen:
            seen.add(n)
            out.append(n)
    return out


def resolve_module(target: str, importer: str, files: set[str]) -> str | None:
    """Resolve a raw import target to a repo-relative file path, if possible."""
    if target.startswith(("./", "../", "/")):
        base = os.path.normpath(os.path.join(os.path.dirname(importer), target))
        return _probe(base, files)
    if target.startswith("."):
        if dialect_of(importer) != "python":
            return None  # npm deep import: needs real resolution
        # python relative import: strip the dots and walk up the package
        dots = len(target) - len(target.lstrip("."))
        rest = target[dots:]
        parts = importer.split("/")[:-1]
        up = max(0, dots - 1)
        base_dir = "/".join(parts[: len(parts) - up] if up else parts)
        rel = "/".join(p for p in (base_dir, rest.replace(".", "/")) if p)
        return _probe(rel, files)
    cand = _probe(target, files)
    if cand:
        return cand
    for prefix in ("src/", "lib/", "app/", "internal/", "pkg/"):
        cand = _probe(prefix + target, files)
        if cand:
            return cand
    # python absolute import of a module living elsewhere in the tree
    tail = target.replace(".", "/")
    for f in files:
        if f == tail + ".py" or f.endswith("/" + tail + ".py"):
            return f
    return None


def _probe(base: str, files: set[str]) -> str | None:
    base = base.replace(os.sep, "/").rstrip("/")
    if not base:
        return None
    if base in files:
        return base
    for ext in (".py", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".go", ".rs", ".rb", ".java"):
        for probe in (base + ext, base + "/index" + ext, base + "/__init__" + ext):
            if probe in files:
                return probe
    return None


def truncate(text: str, limit: int = 4000) -> str:
    if len(text) <= limit:
        return text
    return text[:limit] + f"\n... [{len(text) - limit} more characters truncated]"